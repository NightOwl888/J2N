using J2N.Text.CodeGen.Metadata;
using J2N.Text.CodeGen.Projection;
using System.Text;

namespace J2N.Text.CodeGen.Generation
{
    public sealed class CSharpFacadeEmitter
    {
        public string EmitFacade(
            ProjectedTypeModel model,
            string backingFieldName,
            FacadeEmitterOptions? options = null)
        {
            options ??= new FacadeEmitterOptions();

            bool wrapMembersInLock = options.WrapMembersInLock;

            var sb = new StringBuilder();

            EmitHeader(sb);

            foreach (string @using in model.Source.Usings.Distinct())
            {
                sb.AppendLine($"using {@using};");
            }

            sb.AppendLine();

            sb.AppendLine($"namespace {model.Namespace}");
            sb.AppendLine("{");
            sb.AppendLine();

            sb.AppendLine($"    public sealed partial class {model.Name}");
            sb.AppendLine("    {");

            foreach (PropertyModel property in model.Properties)
            {
                bool suppressDocs =
                    options.SuppressMissingDocumentationWarnings
                    && !HasDocumentation(property.Documentation, property.IndexParameters);

                if (suppressDocs)
                {
                    sb.AppendLine("#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member");
                }

                EmitDocumentation(sb, property.Documentation, property.IndexParameters);
                EmitAttributes(sb, property.Attributes, "        ");
                EmitProperty(sb, property, backingFieldName, wrapMembersInLock);

                if (suppressDocs)
                {
                    sb.AppendLine("#pragma warning restore CS1591 // Missing XML comment for publicly visible type or member");
                    sb.AppendLine();
                }
            }

            string? activeConditional = null;

            foreach (MethodModel method in model.Methods)
            {
                if (method.ConditionalCompilationSymbol
                    != activeConditional)
                {
                    if (activeConditional is not null)
                    {
                        sb.AppendLine("#endif");
                        sb.AppendLine();
                    }

                    activeConditional =
                        method.ConditionalCompilationSymbol;

                    if (activeConditional is not null)
                    {
                        sb.AppendLine(
                            $"#if {activeConditional}");
                    }
                }

                bool suppressDocs =
                    options.SuppressMissingDocumentationWarnings
                    && !HasDocumentation(
                        method.Documentation,
                        method.Parameters);

                if (suppressDocs)
                {
                    sb.AppendLine(
                        "#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member");
                }

                EmitDocumentation(
                    sb,
                    method.Documentation,
                    method.Parameters);

                EmitAttributes(
                    sb,
                    method.Attributes,
                    "        ");

                EmitMethod(
                    sb,
                    method,
                    model.Name,
                    model.Source.SourceType,
                    backingFieldName,
                    wrapMembersInLock);

                if (suppressDocs)
                {
                    sb.AppendLine(
                        "#pragma warning restore CS1591 // Missing XML comment for publicly visible type or member");

                    sb.AppendLine();
                }
            }

            if (activeConditional is not null)
            {
                sb.AppendLine("#endif");
                sb.AppendLine();
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void EmitHeader(
            StringBuilder sb)
        {
            sb.AppendLine("//------------------------------------------------------------------------------");
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     This code was generated by a tool.");
            sb.AppendLine("//");
            sb.AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if");
            sb.AppendLine("//     the code is regenerated.");
            sb.AppendLine("//");
            sb.AppendLine("//     Instead of editing this file, the MutableTextBuffer*.cs files should be edited");
            sb.AppendLine("//     which will propagate the edits to this file.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("//------------------------------------------------------------------------------");

            sb.AppendLine("#nullable enable");
            sb.AppendLine();
        }

        private static void EmitMethod(
            StringBuilder sb,
            MethodModel method,
            string facadeName,
            string sourceType,
            string backingFieldName,
            bool wrapMembersInLock)
        {
            string parameterList =
                string.Join(
                    ", ",
                    method.Parameters.Select(FormatParameter));

            string genericParameterList =
                method.GenericParameters.Count == 0
                    ? ""
                    : "<" + string.Join(", ", method.GenericParameters.Select(p => p.Name)) + ">";

            string argumentList =
                string.Join(
                    ", ",
                    method.Parameters.Select(
                        p => GetArgumentExpression(
                            p,
                            sourceType,
                            backingFieldName)));

            string returnType =
                method.ReturnsSelf
                    ? facadeName
                    : method.ReturnType;

            string unsafeModifier = method.IsUnsafe ? " unsafe" : "";
            string modifier = IsObjectMethod(method) ? " override" : "";

            sb.AppendLine($"        public{modifier}{unsafeModifier} {returnType} {method.Name}{genericParameterList}({parameterList})");
            foreach (GenericParameterModel parameter in method.GenericParameters)
            {
                if (parameter.Constraints.Count == 0)
                {
                    continue;
                }

                sb.Append("            where ");
                sb.Append(parameter.Name);
                sb.Append(" : ");
                sb.AppendLine(string.Join(", ", parameter.Constraints));
            }
            sb.AppendLine("        {");

            if (wrapMembersInLock)
            {
                sb.AppendLine("            lock (syncRoot)");
                sb.AppendLine("            {");

                if (method.IsBuilderMethod && method.ReturnsSelf)
                {
                    sb.AppendLine($"                {backingFieldName}.{method.Name}({argumentList});");
                    sb.AppendLine("                return this;");
                }
                else if (method.ReturnType == "void")
                {
                    sb.AppendLine($"                {backingFieldName}.{method.Name}({argumentList});");
                }
                else
                {
                    sb.AppendLine($"                return {backingFieldName}.{method.Name}({argumentList});");
                }

                sb.AppendLine("            }");
            }
            else
            {
                if (method.IsBuilderMethod && method.ReturnsSelf)
                {
                    sb.AppendLine($"            {backingFieldName}.{method.Name}({argumentList});");
                    sb.AppendLine("            return this;");
                }
                else if (method.ReturnType == "void")
                {
                    sb.AppendLine($"            {backingFieldName}.{method.Name}({argumentList});");
                }
                else
                {
                    sb.AppendLine($"            return {backingFieldName}.{method.Name}({argumentList});");
                }
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitProperty(
            StringBuilder sb,
            PropertyModel property,
            string backingFieldName,
            bool wrapMembersInLock)
        {
            string unsafeModifier = property.IsUnsafe ? " unsafe" : "";

            if (!property.IsIndexer)
            {
                sb.AppendLine($"        public{unsafeModifier} {property.TypeName} {property.Name}");
                sb.AppendLine("        {");

                if (property.HasGetter)
                {
                    if (wrapMembersInLock)
                    {
                        sb.AppendLine("            get");
                        sb.AppendLine("            {");

                        sb.AppendLine("                lock (syncRoot)");
                        sb.AppendLine("                {");
                        sb.AppendLine($"                    return {backingFieldName}.{property.Name};");
                        sb.AppendLine("                }");

                        sb.AppendLine("            }");
                    }
                    else
                    {
                        sb.AppendLine($"            get => {backingFieldName}.{property.Name};");
                    }
                }

                if (property.HasSetter)
                {
                    if (wrapMembersInLock)
                    {
                        sb.AppendLine("            set");
                        sb.AppendLine("            {");

                        sb.AppendLine("                lock (syncRoot)");
                        sb.AppendLine("                {");
                        sb.AppendLine($"                    {backingFieldName}.{property.Name} = value;");
                        sb.AppendLine("                }");

                        sb.AppendLine("            }");
                    }
                    else
                    {
                        sb.AppendLine($"            set => {backingFieldName}.{property.Name} = value;");
                    }
                }

                sb.AppendLine("        }");
                sb.AppendLine();
                return;
            }

            // Indexer
            string indexParams =
                string.Join(", ",
                    property.IndexParameters.Select(p => $"{p.TypeName} {p.Name}"));

            string args =
                string.Join(", ",
                    property.IndexParameters.Select(p => p.Name));

            sb.AppendLine($"        public{unsafeModifier} {property.TypeName} this[{indexParams}]");
            sb.AppendLine("        {");

            if (property.HasGetter)
            {
                if (wrapMembersInLock)
                {
                    sb.AppendLine("            get");
                    sb.AppendLine("            {");

                    sb.AppendLine("                lock (syncRoot)");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    return {backingFieldName}[{args}];");
                    sb.AppendLine("                }");

                    sb.AppendLine("            }");
                }
                else
                {
                    sb.AppendLine($"            get => {backingFieldName}[{args}];");
                }
            }

            if (property.HasSetter)
            {
                if (wrapMembersInLock)
                {
                    sb.AppendLine("            set");
                    sb.AppendLine("            {");

                    sb.AppendLine("                lock (syncRoot)");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    {backingFieldName}[{args}] = value;");
                    sb.AppendLine("                }");

                    sb.AppendLine("            }");
                }
                else
                {
                    sb.AppendLine($"            set => {backingFieldName}[{args}] = value;");
                }
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitAttributes(
            StringBuilder sb,
            IEnumerable<AttributeModel> attributes,
            string indent)
        {
            foreach (AttributeModel attribute in attributes
                .Where(a =>
                    a.Name != "CodeGenerationIgnore"
                    && a.Name != "CodeGenerationReturnsSelf"))
            {
                if (attribute.Arguments.Count == 0)
                {
                    sb.AppendLine($"{indent}[{attribute.Name}]");
                }
                else
                {
                    string args = string.Join(", ", attribute.Arguments);

                    sb.AppendLine($"{indent}[{attribute.Name}({args})]");
                }
            }
        }

        private static void EmitDocumentation(
            StringBuilder sb,
            DocumentationModel? docs,
            IEnumerable<ParameterModel> parameters)
        {
            if (docs is null && !parameters.Any())
                return;

            EmitXmlElement(sb, "summary", docs?.SummaryXml);

            foreach (ParameterModel parameter in parameters)
            {
                EmitParamDocumentation(sb, parameter);
            }

            EmitXmlElement(sb, "returns", docs?.ReturnsXml);

            EmitXmlElement(sb, "remarks", docs?.RemarksXml);
        }

        private static void EmitParamDocumentation(
            StringBuilder sb,
            ParameterModel parameter)
        {
            if (string.IsNullOrWhiteSpace(parameter.Documentation))
                return;

            sb.AppendLine($"        /// <param name=\"{parameter.Name}\">");

            foreach (string line in NormalizeLines(parameter.Documentation))
            {
                sb.AppendLine($"        /// {line.TrimEnd()}");
            }

            sb.AppendLine("        /// </param>");
        }

        private static void EmitXmlElement(
            StringBuilder sb,
            string elementName,
            string? content)
        {
            if (string.IsNullOrWhiteSpace(content))
                return;

            sb.AppendLine($"        /// <{elementName}>");

            foreach (string line in NormalizeLines(content))
            {
                sb.AppendLine($"        /// {line.TrimEnd()}");
            }

            sb.AppendLine($"        /// </{elementName}>");
        }

        private static bool IsObjectMethod(MethodModel method)
        {
            if (method.Name == "ToString"
                && method.Parameters.Count == 0)
            {
                return true;
            }

            if (method.Name == "GetHashCode"
                && method.Parameters.Count == 0)
            {
                return true;
            }

            if (method.Name == "Equals"
                && method.Parameters.Count == 1 && (method.Parameters[0].TypeName == "object?" || method.Parameters[0].TypeName == "object"))
            {
                return true;
            }

            return false;
        }

        private static bool HasDocumentation(
            DocumentationModel? docs,
            IEnumerable<ParameterModel> parameters)
        {
            if (docs is not null)
            {
                if (!string.IsNullOrWhiteSpace(docs.SummaryXml)
                    || !string.IsNullOrWhiteSpace(docs.ReturnsXml)
                    || !string.IsNullOrWhiteSpace(docs.RemarksXml))
                {
                    return true;
                }
            }

            return parameters.Any(p =>
                !string.IsNullOrWhiteSpace(p.Documentation));
        }

        private static string GetArgumentExpression(
            ParameterModel parameter,
            string sourceType,
            string backingFieldName)
        {
            if (parameter.SourceTypeName == sourceType + "?")
            {
                return $"{parameter.Name}?.{backingFieldName}";
            }

            if (parameter.SourceTypeName == sourceType)
            {
                return $"{parameter.Name}.{backingFieldName}";
            }

            return parameter.Name;
        }

        private static string FormatParameter(ParameterModel parameter)
        {
            string modifier =
                string.IsNullOrWhiteSpace(parameter.Modifier)
                    ? ""
                    : parameter.Modifier + " ";

            return
                $"{modifier}{parameter.TypeName} {parameter.Name}";
        }

        private static IEnumerable<string> NormalizeLines(string text)
        {
            string normalized =
                text.Replace("\r\n", "\n")
                    .Replace('\r', '\n');

            return normalized
                .Split('\n')
                .Select(l =>
                {
                    string line = l.TrimEnd();

                    string trimmed = line.TrimStart();

                    if (trimmed.StartsWith("///"))
                    {
                        trimmed = trimmed.Substring(3);

                        if (trimmed.StartsWith(" "))
                        {
                            trimmed = trimmed.Substring(1);
                        }

                        return trimmed;
                    }

                    return line;
                });
        }
    }
}
