using System.Linq;
using System.Text;
using J2N.Text.CodeGen.Metadata;

namespace J2N.Text.CodeGen.Generation
{
    public sealed class CSharpFacadeEmitter
    {
        public string EmitFacade(
            TypeModel model,
            string facadeNamespace,
            string facadeName,
            string backingFieldName)
        {
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated />");
            sb.AppendLine();

            sb.AppendLine($"namespace {facadeNamespace}");
            sb.AppendLine("{");
            sb.AppendLine();

            sb.AppendLine($"    public partial class {facadeName}");
            sb.AppendLine("    {");

            foreach (MethodModel method in model.Methods)
            {
                EmitMethod(sb, method, facadeName, backingFieldName);
            }

            foreach (PropertyModel property in model.Properties)
            {
                EmitProperty(sb, property, backingFieldName);
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void EmitMethod(
            StringBuilder sb,
            MethodModel method,
            string facadeName,
            string backingFieldName)
        {
            string parameterList =
                string.Join(
                    ", ",
                    method.Parameters.Select(p => $"{p.TypeName} {p.Name}"));

            string argumentList =
                string.Join(
                    ", ",
                    method.Parameters.Select(p => p.Name));

            string returnType =
                method.ReturnsSelf
                    ? facadeName
                    : method.ReturnType;

            sb.AppendLine($"        public {returnType} {method.Name}({parameterList})");
            sb.AppendLine("        {");

            if (method.ReturnsSelf)
            {
                sb.AppendLine($"            {backingFieldName}.{method.Name}({argumentList});");
                sb.AppendLine("            return this;");
            }
            else if (method.ReturnType == "void")
            {
                sb.AppendLine($"            {backingFieldName}.{method.Name}({argumentList});");
            }
            else
            {
                sb.AppendLine($"            return {backingFieldName}.{method.Name}({argumentList});");
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitProperty(
            StringBuilder sb,
            PropertyModel property,
            string backingFieldName)
        {
            if (property.IsIndexer)
            {
                string parameterList =
                    string.Join(
                        ", ",
                        property.IndexParameters.Select(p => $"{p.TypeName} {p.Name}"));

                string argumentList =
                    string.Join(
                        ", ",
                        property.IndexParameters.Select(p => p.Name));

                sb.AppendLine($"        public {property.TypeName} this[{parameterList}]");
                sb.AppendLine("        {");

                if (property.HasGetter)
                {
                    sb.AppendLine($"            get => {backingFieldName}[{argumentList}];");
                }

                if (property.HasSetter)
                {
                    sb.AppendLine($"            set => {backingFieldName}[{argumentList}] = value;");
                }

                sb.AppendLine("        }");
            }
            else
            {
                sb.AppendLine($"        public {property.TypeName} {property.Name}");
                sb.AppendLine("        {");

                if (property.HasGetter)
                {
                    sb.AppendLine($"            get => {backingFieldName}.{property.Name};");
                }

                if (property.HasSetter)
                {
                    sb.AppendLine($"            set => {backingFieldName}.{property.Name} = value;");
                }

                sb.AppendLine("        }");
            }

            sb.AppendLine();
        }
    }
}
